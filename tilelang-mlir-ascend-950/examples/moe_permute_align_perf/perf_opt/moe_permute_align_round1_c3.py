"""Stage 4 Round 1 candidate C3: ``expert_ids`` by expert-side expansion.

Parent: ``moe_permute_align_round1_c1.py`` (current best).  One main
optimization point: the block-owner array stops costing ``O(num_experts)``
serial lane ops per block.

Stage 3 derives every block's owner with a rank count -- ``for e in
T.serial(E): cnt += (cumsum[e] <= b*B)`` -- which is ``E`` vector ops per block
round and dominated the small geometries (12-35 us of the 15-43 us measured
there).  Here each expert instead *expands* the block range it owns
(``[cumsum[e]/B, cumsum[e+1]/B)``), so the work is one store per block, and the
blocks past the padded length are cleared by a separate disjoint guard (the two
write sets cannot overlap, so no ordering between them is needed).
"""

