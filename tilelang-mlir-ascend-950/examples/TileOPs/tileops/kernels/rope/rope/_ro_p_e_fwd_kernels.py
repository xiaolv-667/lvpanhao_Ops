# The GPU source decorates this factory with ``@target_cache(maxsize=32)``
# (tileops._kernels.build_target, i.e. one compiled program per argument tuple).
# The extraction script emits function bodies only, so the decorator is absent
# here and the NPU kernel component restores an equivalent compile cache for the
