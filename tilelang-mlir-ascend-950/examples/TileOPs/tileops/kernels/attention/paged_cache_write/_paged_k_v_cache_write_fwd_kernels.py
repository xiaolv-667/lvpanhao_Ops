# --- external imports (preserved) ---
from collections.abc import Callable
import tilelang
# NPU dialect: ``SimtVF`` (the VF block Ascend requires) lives only here, so the
# extracted GPU body's ``tilelang.language`` import does not cover it.
import tilelang.ascend.language as T

# Vector width of the SIMT vector-fork block the vectorised body runs in.
_SIMT_VF_THREADS = 256

# Largest finite magnitude float8_e4m3fn represents (torch.finfo(...).max).
_FP8_E4M3_MAX = 448.0

# --- TileLang kernel functions (@tilelang.jit, Ascend target) ---
def _paged_cache_write_kernel(
    heads_kv: int,
    dim: int,
    physical_tokens: int,
    in_dtype: str,
    cache_dtype: str,
) -> Callable:
    row_width = heads_kv * dim
    quantized = cache_dtype == "float8_e4m3fn"

    @tilelang.jit(out_idx=[], target="ascend")
    def _func(block_rows: int, block_cols: int) -> Callable:
        # The tokens written are a dynamic extent: a decode step writes one row per
        # running request, and a kernel built per token count would compile every step.
        tokens = T.dynamic("tokens")
        # Ascend has a single grid extent, so the column tiling is folded into it.
        n_col_tiles = (row_width + block_cols - 1) // block_cols
        grid = T.ceildiv(tokens, block_rows) * n_col_tiles
        # One flat parallel extent per block: block_rows * block_cols elements.
        flat = block_rows * block_cols

        if quantized:

            @T.prim_func
            def _paged_cache_write_fp8(
                K: T.Tensor((tokens, row_width), in_dtype),  # type: ignore
                V: T.Tensor((tokens, row_width), in_dtype),  # type: ignore
                KPages: T.Tensor((physical_tokens, row_width), cache_dtype),  # type: ignore
                VPages: T.Tensor((physical_tokens, row_width), cache_dtype),  # type: ignore
                Slots: T.Tensor((tokens,), "int64"),  # type: ignore
                KScale: T.Tensor((1,), "float32"),  # type: ignore
                VScale: T.Tensor((1,), "float32"),  # type: ignore
            ) -> None:
                with T.Kernel(grid) as bx:
                    row_tile = bx // n_col_tiles
                    col_tile = bx % n_col_tiles
                    with T.SimtVF(threads=_SIMT_VF_THREADS):
                        for idx in T.Parallel(flat):
                            row = idx // block_cols
                            col_in_block = idx % block_cols
                            token = row_tile * block_rows + row
                            col = col_tile * block_cols + col_in_block
                            if token < tokens and col < row_width:
                                slot = Slots[token]
                                if slot >= 0:
                                    # The Ascend FP8 cast maps finite overflow and
                                    # infinities to NaN, where the contract saturates
                                    # them, so the value is clamped before the store.
                                    # The clamp keeps NaN intact (min/max return NaN
                                    # when handed one), matching the reference, which
                                    # clamps and lets NaN through the same way.
                                    KPages[slot, col] = T.max(
                                        T.min(T.Cast("float32", K[token, col]) / KScale[0], _FP8_E4M3_MAX),
                                        -_FP8_E4M3_MAX,
                                    )
                                    VPages[slot, col] = T.max(
                                        T.min(T.Cast("float32", V[token, col]) / VScale[0], _FP8_E4M3_MAX),
                                        -_FP8_E4M3_MAX,
                                    )

            return _paged_cache_write_fp8

        @T.prim_func
        def _paged_cache_write_16bit(
            K: T.Tensor((tokens, row_width), in_dtype),  # type: ignore
            V: T.Tensor((tokens, row_width), in_dtype),  # type: ignore
            KPages: T.Tensor((physical_tokens, row_width), cache_dtype),  # type: ignore
            VPages: T.Tensor((physical_tokens, row_width), cache_dtype),  # type: ignore
            Slots: T.Tensor((tokens,), "int64"),  # type: ignore
        ) -> None:
            with T.Kernel(grid) as bx:
                row_tile = bx // n_col_tiles
                col_tile = bx % n_col_tiles
                with T.SimtVF(threads=_SIMT_VF_THREADS):
                    for idx in T.Parallel(flat):
                        row = idx // block_cols
                        col_in_block = idx % block_cols
                        token = row_tile * block_rows + row
                        col = col_tile * block_cols + col_in_block
                        if token < tokens and col < row_width:
                            slot = Slots[token]
                            if slot >= 0:
                                KPages[slot, col] = K[token, col]
                                VPages[slot, col] = V[token, col]

        return _paged_cache_write_16bit

    return _func

