"""Generate diagnostic probe modules from the frozen Stage-3 kernel (Stage 4).

Probes are *not* candidates: they exist only to decompose the measured launch time
(which part of the project launch is the cache shift, which part the Cube
projection, what is the launch floor of this grid).  Every probe is derived
mechanically from the read-only baseline source, so nothing here can drift from
the Stage-3 semantics.

Usage (cwd = examples/TileOPs):

    python mkprobe.py            # writes probe_project_noshift.py next to this file
"""

import os

HERE = os.path.dirname(os.path.abspath(__file__))
BASELINE = os.path.abspath(os.path.join(
    HERE, "..", "..", "..", "TileOPs", "tileops", "kernels", "sequence_modeling",
    "engram_decode", "engram_decode_kernel", "_engram_project_kernel.py"))

SHIFT_CALL = """                if nshift > 0:
                    if m0 == 0:
                        shift_ub = T.alloc_shared((nshift, block_n), dtype_str)
                        _shift_cache(conv_state, new_conv_state, shift_ub, n0, an)
"""


SHIFT_LOOP = """        for b in T.serial(batch):
            T.copy(conv_state[b, 1:max_conv_len, n0 : n0 + an], shift_ub[0:nshift, 0:an])
            T.copy(shift_ub[0:nshift, 0:an], new_conv_state[b, 0:nshift, n0 : n0 + an])
"""

TINY_LOOP = """        for b in T.serial(1):
            T.copy(conv_state[b, 1:2, n0 : n0 + an], shift_ub[0:1, 0:an])
            T.copy(shift_ub[0:1, 0:an], new_conv_state[b, 0:1, n0 : n0 + an])
"""

STEP_BASELINE = os.path.join(os.path.dirname(BASELINE), "_engram_step_kernel.py")

# PROBE: only one of the four block reductions is finalised (3 AllReduce calls
# dropped).  The arithmetic is wrong on purpose -- this probe measures the
# marginal cost of the 3 extra AscendAllReduce barrier chains and nothing else.
STEP_FINALIZE = """                T.finalize_reducer(acc_k, sk)
                T.finalize_reducer(acc_p, sp)
                T.finalize_reducer(acc_v, sv)
"""


def main():
    with open(BASELINE) as f:
        src = f.read()
    with open(STEP_BASELINE) as f:
        stepsrc = f.read()
    assert STEP_FINALIZE in stepsrc
    out = stepsrc.replace(STEP_FINALIZE, "")
    out = out.replace(
        '"""`_engram_step_kernel` on Ascend 950PR (SIMT): launch 2 of 2 of EngramDecodeFwdOp.',
        '"""PROBE (Stage 4 diagnostic): step kernel with 3 of the 4 block reductions removed.\n\n'
        'Generated by `perf_opt/experiments/mkprobe.py`; NOT a candidate (the arithmetic is\n'
        'deliberately wrong).  `baseline - probe` is the cost of 3 AscendAllReduce chains.\n\n'
        'Original docstring follows.')
    path = os.path.join(HERE, "probe_step_1reduce.py")
    with open(path, "w") as f:
        f.write(out)
    print(f"wrote {path}")
    assert SHIFT_CALL in src, "baseline shift block changed; update mkprobe.py"
    out = src.replace(SHIFT_CALL, "")
    # keep the factory signature identical so bench_one.py can drive it
    out = out.replace(
        '"""`_engram_project_kernel` on Ascend 950PR: both decode projections + cache shift.',
        '"""PROBE (Stage 4 diagnostic): `_engram_project_kernel` with the cache shift REMOVED.\n\n'
        'Generated by `perf_opt/experiments/mkprobe.py` from the frozen Stage-3 baseline;\n'
        'not a candidate and not adoptable — it measures the Cube projection + launch floor\n'
        'alone, so `baseline - probe` is the cache-shift cost.\n\n'
        'Original docstring follows.\n\n'
        '# `_engram_project_kernel` on Ascend 950PR: both decode projections + cache shift.')
    path = os.path.join(HERE, "probe_project_noshift.py")
    with open(path, "w") as f:
        f.write(out)
    print(f"wrote {path}")

    # PROBE: the cache shift reduced to ONE (batch, row) copy pair, i.e. ~1/16 of
    # the bytes on serving-b4 but the AIV/mix code path still present.  Decides
    # whether the measured shift cost is copy bytes or mix-promotion overhead.
    assert SHIFT_LOOP in src
    tiny = src.replace(SHIFT_LOOP, TINY_LOOP)
    tiny = tiny.replace(
        '"""`_engram_project_kernel` on Ascend 950PR: both decode projections + cache shift.',
        '"""PROBE (Stage 4 diagnostic): project kernel with a 1-row shift copy.\n\n'
        'Generated by `perf_opt/experiments/mkprobe.py`; NOT a candidate (the history\n'
        'shift is deliberately incomplete).  Isolates mix(AIC+AIV) promotion overhead\n'
        'from the shift copy bytes.\n\n'
        'Original docstring follows.')
    path = os.path.join(HERE, "probe_project_tinyshift.py")
    with open(path, "w") as f:
        f.write(tiny)
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
